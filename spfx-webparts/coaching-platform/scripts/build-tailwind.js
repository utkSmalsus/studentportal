// Compiles Tailwind to CSS text and wraps it as a TS string constant, so it
// can be `import`ed by plain TypeScript and injected into a webpart's
// Shadow DOM at runtime (no custom webpack loader needed — SPFx's default
// TS compilation handles a .ts file with no extra config).
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const input = path.join(root, 'src/webparts/studentPortal/styles/tailwind.input.css');
const output = path.join(root, 'src/webparts/studentPortal/styles/tailwindCss.ts');

const css = execSync(`npx tailwindcss -i "${input}" --minify`, {
  cwd: root,
  encoding: 'utf8',
});

fs.writeFileSync(
  output,
  `// AUTO-GENERATED by scripts/build-tailwind.js — do not edit by hand.\nexport const tailwindCss = ${JSON.stringify(css)};\n`
);

console.log(`[build-tailwind] wrote ${path.relative(root, output)} (${css.length} bytes)`);
